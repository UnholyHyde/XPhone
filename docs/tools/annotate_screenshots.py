def make(name,filename,title,items):
    raw=(ROOT/filename).read_bytes()
    with Image.open(ROOT/filename) as im:
        w,h=im.size
    sx=28+(926-w)//2; sy=106
    H=max(h+sy+30,sy+len(items)*122+25)
    p=[f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="1320" height="{H}" viewBox="0 0 1320 {H}" role="img" aria-labelledby="title desc">',
       f'<title id="title">{html.escape(title)}</title><desc id="desc">Реальный снимок XPhone 1.4.0 с пронумерованными выделениями и пояснениями.</desc>',
       f'<rect width="1320" height="{H}" rx="20" fill="#101114"/>',
       '<g font-family="Segoe UI,Arial,sans-serif">',
       f'<text x="28" y="32" fill="#a7a9b0" font-size="13" letter-spacing="2">XPHONE ДЛЯ WINDOWS / ШАГ {name[:2]}</text>',
       f'<text x="28" y="73" fill="#f5f5f7" font-size="28" font-weight="700">{html.escape(title)}</text>',
       f'<image x="{sx}" y="{sy}" width="{w}" height="{h}" xlink:href="data:image/jpeg;base64,{base64.b64encode(raw).decode()}"/>']
    for n,(box,heading,lines) in enumerate(items,1):
        x,y,bw,bh=box;x+=sx;y+=sy
        p.append(f'<rect x="{x}" y="{y}" width="{bw}" height="{bh}" rx="8" fill="none" stroke="#f8fafc" stroke-width="2"/>')
        cx=x+bw-9;cy=y-14
        p.append(f'<path d="M {cx-19} {cy+3} L {cx-33} {cy+21} m 0 -7 v 7 h 7" fill="none" stroke="#f8fafc" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/>')
        p.append(f'<circle cx="{cx}" cy="{cy}" r="14" fill="#f8fafc" stroke="#101114" stroke-width="2"/>')
        p.append(f'<text x="{cx}" y="{cy+5}" text-anchor="middle" font-size="14" font-weight="800" fill="#101114">{n}</text>')
        ly=sy+(n-1)*122
        p.append(f'<rect x="982" y="{ly}" width="310" height="106" rx="12" fill="#1b1d22" stroke="#34363c"/>')
        p.append(f'<text x="998" y="{ly+27}" fill="#f5f5f7" font-size="16" font-weight="700">{n}. {html.escape(heading)}</text>')
        for j,line in enumerate(lines):
            p.append(f'<text x="998" y="{ly+53+j*21}" fill="#b9bbc4" font-size="13">{html.escape(line)}</text>')
    p.append('</g></svg>')
    (ROOT/(name+'.svg')).write_text('\n'.join(p),encoding='utf-8')

